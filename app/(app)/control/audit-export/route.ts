import { NextResponse } from "next/server";
import { getWorkspace } from "@/lib/workspace";
import { can } from "@/lib/roles";
import { db } from "@/lib/stock";
import { toCsv } from "@/lib/format";

/** Owner export of the full audit trail (evidence retention). Read-only; RLS limits rows to audit.view holders. */
export async function GET() {
  const ws = await getWorkspace();
  if (!ws || ws.aal !== "aal2" || !can(ws, "audit.view")) return new NextResponse("Unauthorized", { status: 401 });
  const supabase = await db();
  const rows: Record<string, unknown>[] = [];
  for (let from = 0; ; from += 1000) {
    const { data, error } = await supabase.from("audit_log")
      .select("id, created_at, actor_membership_id, action, entity, entity_id, reason, before_data, after_data, correlation_id")
      .order("id").range(from, from + 999);
    if (error) return new NextResponse("Error", { status: 500 });
    rows.push(...(data ?? []));
    if (!data || data.length < 1000) break;
  }
  const { data: members } = await supabase.from("memberships").select("id, display_name");
  const who = new Map((members ?? []).map((m) => [m.id, m.display_name]));
  const csv = toCsv([
    ["DIROMA Business OS — audit log export"], ["Generated", new Date().toISOString()], ["Generated by", ws.display_name], ["Rows", rows.length], [],
    ["id", "created_at_utc", "actor", "action", "entity", "entity_id", "reason", "before", "after", "correlation_id"],
    ...rows.map((r) => [r.id, r.created_at, (r.actor_membership_id && who.get(String(r.actor_membership_id))) || "system", r.action, r.entity, r.entity_id,
      r.reason, r.before_data ? JSON.stringify(r.before_data) : "", r.after_data ? JSON.stringify(r.after_data) : "", r.correlation_id]),
  ]);
  return new NextResponse("﻿" + csv, { headers: { "Content-Type": "text/csv; charset=utf-8",
    "Content-Disposition": `attachment; filename="diroma-audit-${new Date().toISOString().slice(0, 10)}.csv"`, "Cache-Control": "private, no-store" } });
}
