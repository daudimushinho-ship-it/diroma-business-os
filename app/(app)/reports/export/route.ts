import { NextResponse, type NextRequest } from "next/server";
import { getWorkspace } from "@/lib/workspace";
import { can } from "@/lib/roles";
import { getLang } from "@/lib/lang";
import { REPORT_KINDS, reportCsvRows, reportLabels, reportSections, type ReportKind } from "@/lib/report-docs";
import { resolvePeriod } from "@/lib/periods";
import { businessToday, toCsv } from "@/lib/format";
import { fetchReport } from "@/lib/reports";
import { renderReportPdf } from "@/lib/pdf";

/** Read-only export. Authorization is enforced again inside the database report function. */
export async function GET(req: NextRequest) {
  const ws = await getWorkspace();
  if (!ws || (ws.mfa_required && ws.aal !== "aal2") || !can(ws, "reports.view")) return new NextResponse("Unauthorized", { status: 401 });
  const q = req.nextUrl.searchParams;
  const kind = q.get("kind") ?? "sales";
  if (!(REPORT_KINDS as readonly string[]).includes(kind)) return new NextResponse("Bad request", { status: 400 });
  const p = resolvePeriod(q.get("preset") ?? "custom", businessToday(), q.get("from") ?? undefined, q.get("to") ?? undefined);
  const lang = await getLang();
  const { data, error } = await fetchReport(kind as ReportKind, p.from, p.to);
  if (error) return new NextResponse("Forbidden", { status: 403 });
  if (data === null) return new NextResponse("Not available for your role", { status: 403 });
  const sections = reportSections(kind as ReportKind, data, lang);
  const title = reportLabels(lang)[kind as ReportKind];
  const generatedAt = new Date().toISOString();
  const ref = `${kind}-${p.from}-${p.to}-${generatedAt.slice(11, 19).replace(/:/g, "")}`;
  const name = `diroma-${kind}-${p.from}-${p.to}`;
  if (q.get("format") === "pdf") {
    const pdf = await renderReportPdf({ title, period: `${p.from} to ${p.to}`, timezone: ws.business.timezone, generatedAt, generatedBy: ws.display_name,
      reference: ref, sections, notes: [reportLabels(lang).fiscalNote, ...(can(ws, "costs.view") ? [] : [reportLabels(lang).costsNote])] });
    return new NextResponse(Buffer.from(pdf), { headers: { "Content-Type": "application/pdf", "Content-Disposition": `attachment; filename="${name}.pdf"`, "Cache-Control": "private, no-store" } });
  }
  const csv = toCsv([[`DIROMA Business OS — ${title}`], ["Period", `${p.from} to ${p.to}`], ["Timezone", ws.business.timezone], ["Currency", "TZS"],
    ["Generated", generatedAt], ["Generated by", ws.display_name], ["Reference", ref], [], ...reportCsvRows(sections)]);
  return new NextResponse("﻿" + csv, { headers: { "Content-Type": "text/csv; charset=utf-8", "Content-Disposition": `attachment; filename="${name}.csv"`, "Cache-Control": "private, no-store" } });
}
