import { NextResponse, type NextRequest } from "next/server";
import { getWorkspace } from "@/lib/workspace";
import { db } from "@/lib/stock";
import { addDays, businessDayStart, toCsv } from "@/lib/format";

/** Read-only CSV export of the period report. Authorization is enforced again by the database function. */
export async function GET(req: NextRequest) {
  const ws = await getWorkspace();
  if (!ws || (ws.mfa_required && ws.aal !== "aal2")) return new NextResponse("Unauthorized", { status: 401 });
  const loc = req.nextUrl.searchParams.get("loc") ?? "";
  const from = req.nextUrl.searchParams.get("from") ?? "";
  const to = req.nextUrl.searchParams.get("to") ?? "";
  if (!/^[0-9a-f-]{36}$/.test(loc) || !/^\d{4}-\d{2}-\d{2}$/.test(from) || !/^\d{4}-\d{2}-\d{2}$/.test(to)) {
    return new NextResponse("Bad request", { status: 400 });
  }
  const supabase = await db();
  const { data, error } = await supabase.rpc("stock_period_report", { p_location: loc, p_from: businessDayStart(from), p_to: businessDayStart(addDays(to, 1)) });
  if (error) return new NextResponse("Forbidden", { status: 403 });
  const { data: dir } = await supabase.rpc("location_directory");
  const locName = ((dir ?? []) as { id: string; name: string }[]).find((l) => l.id === loc)?.name ?? loc;
  const rows = (data ?? []) as Record<string, string | number>[];
  const csv = toCsv([
    ["DIROMA Business OS — Stock movement report"],
    ["Location", locName], ["Period", `${from} to ${to}`], ["Timezone", "Africa/Dar_es_Salaam"], ["Unit", "pcs"],
    ["Generated", new Date().toISOString()], ["Generated by", ws.display_name], [],
    ["design_code", "design_name", "color", "size", "opening", "inbound", "outbound", "closing"],
    ...rows.map((r) => [r.design_code, r.design_name, r.color, r.size, Number(r.opening), Number(r.inbound), Number(r.outbound), Number(r.closing)]),
  ]);
  return new NextResponse("﻿" + csv, {
    headers: {
      "Content-Type": "text/csv; charset=utf-8",
      "Content-Disposition": `attachment; filename="diroma-stock-${from}-${to}.csv"`,
      "Cache-Control": "private, no-store",
    },
  });
}
