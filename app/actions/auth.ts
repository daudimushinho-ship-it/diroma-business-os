"use server";
import { redirect } from "next/navigation";
import { createClient } from "@/lib/supabase/server";
import { createAdminClient } from "@/lib/supabase/admin";
import { authPlaceholderEmail, normalizePhone } from "@/lib/phone";
import { checkNewPassword, normalizeCode } from "@/lib/password";
import { LANDING, needsMfa, type Workspace } from "@/lib/roles";
import type { ErrorKey } from "@/lib/i18n";

export type FormState = { error?: ErrorKey; ok?: boolean } | undefined;

function str(fd: FormData, k: string): string {
  const v = fd.get(k);
  return typeof v === "string" ? v : "";
}

/** Phone + password sign-in. Generic error for unknown number or wrong password. */
export async function signIn(_prev: FormState, fd: FormData): Promise<FormState> {
  const supabase = await createClient();
  if (!supabase) return { error: "not_configured" };
  const phone = normalizePhone(str(fd, "phone"));
  const password = str(fd, "password"); // used exactly as typed — never trimmed
  if (!phone.ok || !password) return { error: "invalid_credentials" };

  const { error } = await supabase.auth.signInWithPassword({ phone: phone.e164, password });
  if (error) {
    // Never log credentials. Distinguish only infrastructure failures from bad credentials.
    if (error.status === undefined || error.status >= 500) return { error: "network" };
    return { error: "invalid_credentials" };
  }

  const { data: ws } = await supabase.rpc("my_workspace");
  if (!ws) {
    await supabase.auth.signOut();
    return { error: "inactive" };
  }
  const workspace = ws as Workspace;
  redirect(needsMfa(workspace) ? "/security/mfa" : LANDING[workspace.role]);
}

export async function signOut() {
  const supabase = await createClient();
  await supabase?.auth.signOut();
  redirect("/login");
}

/**
 * Staff activation: phone + one-time code from the Owner + the worker's own new password.
 * Order: verify code (counts attempts) → set password → consume code & activate membership.
 * If the last step fails the account stays 'pending_activation' (no business access) and can be retried.
 */
export async function activateAccount(_prev: FormState, fd: FormData): Promise<FormState> {
  const admin = createAdminClient();
  const supabase = await createClient();
  if (!admin || !supabase) return { error: "not_configured" };
  const phone = normalizePhone(str(fd, "phone"));
  if (!phone.ok) return { error: "invalid_phone" };
  const code = normalizeCode(str(fd, "code"));
  const pw = checkNewPassword(str(fd, "password"), str(fd, "confirm"));
  if (!pw.ok) return { error: pw.error };
  if (code.length < 6) return { error: "invalid_code" };

  const { data: userId, error: checkErr } = await admin.rpc("activation_check", { p_phone: phone.e164, p_code: code });
  if (checkErr || !userId) return { error: "invalid_code" };

  const { error: pwErr } = await admin.auth.admin.updateUserById(userId as string, { password: str(fd, "password") });
  if (pwErr) return { error: "generic" };

  const { error: finErr } = await admin.rpc("activation_finalize", { p_phone: phone.e164, p_code: code });
  if (finErr) return { error: "generic" };

  const { error: signErr } = await supabase.auth.signInWithPassword({ phone: phone.e164, password: str(fd, "password") });
  if (signErr) redirect("/login");
  redirect("/");
}

/**
 * One-time Owner bootstrap. Requires the setup code generated by scripts/setup-owner.mjs.
 * Partial failure (auth user created, membership not) deletes the auth user so a retry is clean.
 */
export async function setupOwner(_prev: FormState, fd: FormData): Promise<FormState> {
  const admin = createAdminClient();
  const supabase = await createClient();
  if (!admin || !supabase) return { error: "not_configured" };
  const phone = normalizePhone(str(fd, "phone"));
  if (!phone.ok) return { error: "invalid_phone" };
  const name = str(fd, "name").trim();
  if (name.length < 2 || name.length > 80) return { error: "generic" };
  const code = normalizeCode(str(fd, "code"));
  const password = str(fd, "password");
  const pw = checkNewPassword(password, str(fd, "confirm"));
  if (!pw.ok) return { error: pw.error };

  const { data: businessId, error: checkErr } = await admin.rpc("setup_check_owner_code", { p_code: code });
  if (checkErr || !businessId) return { error: "invalid_code" };

  const { data: created, error: createErr } = await admin.auth.admin.createUser({
    phone: phone.e164,
    email: authPlaceholderEmail(phone.e164), // required by Supabase to build the MFA QR code
    email_confirm: true,
    password,
    // Phone possession is attested by the out-of-band setup code + installer verification (documented in docs/SETUP.md).
    phone_confirm: true,
    app_metadata: { enrolled_via: "owner_setup_code" },
  });
  if (createErr || !created.user) return { error: ["phone_exists", "email_exists"].includes(createErr?.code ?? "") ? "duplicate_phone" : "generic" };

  const { error: finErr } = await admin.rpc("setup_finalize_owner", {
    p_code: code, p_user: created.user.id, p_phone: phone.e164, p_name: name,
  });
  if (finErr) {
    await admin.auth.admin.deleteUser(created.user.id); // leave no orphan identity behind
    return { error: "invalid_code" };
  }

  await supabase.auth.signInWithPassword({ phone: phone.e164, password });
  redirect("/security/mfa");
}
